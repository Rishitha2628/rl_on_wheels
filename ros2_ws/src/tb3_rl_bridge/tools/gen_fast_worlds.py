#!/usr/bin/env python3
"""Generate throughput-accelerated variants of the stage worlds.

Reads tb3_stage{1..5}.sdf and emits tb3_stage{N}_fast.sdf next to them,
identical in every respect except <real_time_factor>, which goes from 1.0
(sim advances at wall-clock speed) to 0 (Ignition's "unlimited" sentinel —
integrate as fast as the CPU allows).

Why only that one field:

  real_time_factor does NOT participate in the integration. It is a pacing
  target the physics loop throttles against; the state trajectory it
  produces is bit-identical to the RTF=1.0 world given the same step size
  and the same command sequence. So the fast worlds are a pure throughput
  change with no dynamics change to defend.

  max_step_size is the other obvious speedup (0.001 -> 0.004 buys roughly
  2x) but it *does* change the integration and therefore the trajectories.
  Deliberately left alone: the whole point of the fast worlds is to run the
  high-interaction-budget arm of the experiment, and that arm is only
  comparable to the real-time arm if the dynamics are the same.

Run after gen_stages.py, which produces the stage files this reads:

    python3 tools/gen_stages.py
    python3 tools/gen_fast_worlds.py

Then rebuild so the new worlds land in the install share dir:

    colcon build --packages-select tb3_rl_bridge
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

WORLDS_DIR = Path(__file__).resolve().parent.parent / "worlds"
STAGES = [1, 2, 3, 4, 5]

# The exact physics block the stage worlds are expected to carry. Matched
# strictly so that a future edit to gen_stages.py cannot silently desync the
# fast variants from their sources -- better to fail loudly here than to ship
# an experiment where the two arms differ by more than pacing.
RTF_PATTERN = re.compile(r"<real_time_factor>\s*1\.0\s*</real_time_factor>")
RTF_FAST = "<real_time_factor>0</real_time_factor>"

BANNER = (
    "<!-- GENERATED by tools/gen_fast_worlds.py from {src} - do not edit.\n"
    "     Identical to {src} except real_time_factor 1.0 -> 0 (unlimited).\n"
    "     Pair with the env_bridge_node parameter real_time_pacing:=false,\n"
    "     which waits on the sim clock instead of the wall clock. -->\n"
)


def main() -> int:
    written, failed = [], []

    for stage in STAGES:
        src = WORLDS_DIR / f"tb3_stage{stage}.sdf"
        dst = WORLDS_DIR / f"tb3_stage{stage}_fast.sdf"

        if not src.exists():
            failed.append(f"{src.name}: missing (run gen_stages.py first)")
            continue

        text = src.read_text()
        text, n = RTF_PATTERN.subn(RTF_FAST, text)

        if n != 1:
            failed.append(
                f"{src.name}: expected exactly 1 '<real_time_factor>1.0</...>', "
                f"found {n}. The physics block changed -- update this script."
            )
            continue

        # Banner goes after the <?xml ...?> declaration so the file stays valid.
        lines = text.split("\n", 1)
        if lines[0].startswith("<?xml"):
            text = lines[0] + "\n" + BANNER.format(src=src.name) + lines[1]
        else:
            text = BANNER.format(src=src.name) + text

        dst.write_text(text)
        written.append(dst.name)

    for name in written:
        print(f"wrote {name}")
    for msg in failed:
        print(f"ERROR {msg}", file=sys.stderr)

    if failed:
        return 1
    print(f"\n{len(written)} fast worlds generated in {WORLDS_DIR}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
